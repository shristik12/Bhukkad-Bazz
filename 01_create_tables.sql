-- 1. STUDENTS
CREATE TABLE STUDENTS (
    STUDENT_ID NUMBER PRIMARY KEY,
    STUDENT_NAME VARCHAR2(100) NOT NULL,
    EMAIL VARCHAR2(100) UNIQUE NOT NULL,
    PHONE VARCHAR2(15),
    DEPARTMENT VARCHAR2(50),
    CREATED_AT DATE DEFAULT SYSDATE
);

-- 2. ADMIN USERS
CREATE TABLE ADMIN_USERS (
    ADMIN_ID NUMBER PRIMARY KEY,
    ADMIN_NAME VARCHAR2(100) NOT NULL,
    USERNAME VARCHAR2(50) UNIQUE NOT NULL,
    PASSWORD_HASH VARCHAR2(255) NOT NULL,
    CREATED_AT DATE DEFAULT SYSDATE
);

-- 3. FOOD ITEMS
CREATE TABLE FOOD_ITEMS (
    FOOD_ID NUMBER PRIMARY KEY,
    FOOD_NAME VARCHAR2(100) NOT NULL,
    CATEGORY VARCHAR2(50),
    PRICE NUMBER(10,2) NOT NULL,
    STOCK_QUANTITY NUMBER DEFAULT 0 NOT NULL,
    IS_AVAILABLE CHAR(1) DEFAULT 'Y',
    CONSTRAINT CHK_FOOD_PRICE CHECK (PRICE >= 0),
    CONSTRAINT CHK_FOOD_STOCK CHECK (STOCK_QUANTITY >= 0),
    CONSTRAINT CHK_FOOD_AVAIL CHECK (IS_AVAILABLE IN ('Y','N'))
);

-- 4. ORDERS
CREATE TABLE ORDERS (
    ORDER_ID NUMBER PRIMARY KEY,
    STUDENT_ID NUMBER NOT NULL,
    ORDER_DATE DATE DEFAULT SYSDATE,
    TOTAL_AMOUNT NUMBER(10,2) DEFAULT 0,
    ORDER_STATUS VARCHAR2(20) DEFAULT 'PLACED',
    CONSTRAINT FK_ORDER_STUDENT
        FOREIGN KEY (STUDENT_ID)
        REFERENCES STUDENTS(STUDENT_ID),
    CONSTRAINT CHK_ORDER_AMOUNT CHECK (TOTAL_AMOUNT >= 0),
    CONSTRAINT CHK_ORDER_STATUS CHECK
        (ORDER_STATUS IN
        ('PLACED','PREPARING','READY','COMPLETED','CANCELLED'))
);

-- 5. ORDER DETAILS
CREATE TABLE ORDER_DETAILS (
    DETAIL_ID NUMBER PRIMARY KEY,
    ORDER_ID NUMBER NOT NULL,
    FOOD_ID NUMBER NOT NULL,
    QUANTITY NUMBER NOT NULL,
    PRICE_AT_ORDER NUMBER(10,2) NOT NULL,
    CONSTRAINT FK_DETAIL_ORDER
        FOREIGN KEY (ORDER_ID)
        REFERENCES ORDERS(ORDER_ID),
    CONSTRAINT FK_DETAIL_FOOD
        FOREIGN KEY (FOOD_ID)
        REFERENCES FOOD_ITEMS(FOOD_ID),
    CONSTRAINT CHK_DETAIL_QTY CHECK (QUANTITY > 0),
    CONSTRAINT CHK_DETAIL_PRICE CHECK (PRICE_AT_ORDER >= 0),
    CONSTRAINT UQ_ORDER_FOOD UNIQUE (ORDER_ID, FOOD_ID)
);

-- 6. PAYMENTS
CREATE TABLE PAYMENTS (
    PAYMENT_ID NUMBER PRIMARY KEY,
    ORDER_ID NUMBER UNIQUE NOT NULL,
    PAYMENT_DATE DATE DEFAULT SYSDATE,
    PAYMENT_AMOUNT NUMBER(10,2) NOT NULL,
    PAYMENT_METHOD VARCHAR2(20),
    PAYMENT_STATUS VARCHAR2(20) DEFAULT 'PENDING',
    CONSTRAINT FK_PAYMENT_ORDER
        FOREIGN KEY (ORDER_ID)
        REFERENCES ORDERS(ORDER_ID),
    CONSTRAINT CHK_PAYMENT_AMOUNT CHECK (PAYMENT_AMOUNT >= 0),
    CONSTRAINT CHK_PAYMENT_METHOD CHECK
        (PAYMENT_METHOD IN ('CASH','UPI','CARD')),
    CONSTRAINT CHK_PAYMENT_STATUS CHECK
        (PAYMENT_STATUS IN ('PENDING','SUCCESS','FAILED','REFUNDED'))
);

-- 7. INVENTORY LOG
CREATE TABLE INVENTORY_LOG (
    LOG_ID NUMBER PRIMARY KEY,
    FOOD_ID NUMBER NOT NULL,
    QUANTITY_CHANGE NUMBER NOT NULL,
    ACTION_TYPE VARCHAR2(30),
    LOG_DATE DATE DEFAULT SYSDATE,
    REMARKS VARCHAR2(255),
    CONSTRAINT FK_INVENTORY_FOOD
        FOREIGN KEY (FOOD_ID)
        REFERENCES FOOD_ITEMS(FOOD_ID)
);

-- 8. ORDER AUDIT
CREATE TABLE ORDER_AUDIT (
    AUDIT_ID NUMBER PRIMARY KEY,
    ORDER_ID NUMBER,
    ACTION_TYPE VARCHAR2(50),
    OLD_STATUS VARCHAR2(20),
    NEW_STATUS VARCHAR2(20),
    ACTION_DATE DATE DEFAULT SYSDATE,
    CONSTRAINT FK_AUDIT_ORDER
        FOREIGN KEY (ORDER_ID)
        REFERENCES ORDERS(ORDER_ID)
);
SELECT TABLE_NAME
FROM USER_TABLES
WHERE TABLE_NAME IN (
    'STUDENTS',
    'ADMIN_USERS',
    'FOOD_ITEMS',
    'ORDERS',
    'ORDER_DETAILS',
    'PAYMENTS',
    'INVENTORY_LOG',
    'ORDER_AUDIT'
)
ORDER BY TABLE_NAME;