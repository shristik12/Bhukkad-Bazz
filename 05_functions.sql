CREATE OR REPLACE FUNCTION CALCULATE_ORDER_BILL (
    P_ORDER_ID IN NUMBER
)
RETURN NUMBER
IS
    V_TOTAL NUMBER(10,2);
    V_COUNT NUMBER;
BEGIN
    SELECT COUNT(*)
    INTO V_COUNT
    FROM ORDERS
    WHERE ORDER_ID = P_ORDER_ID;

    IF V_COUNT = 0 THEN
        RAISE_APPLICATION_ERROR(-20010,
            'Order does not exist.');
    END IF;

    SELECT NVL(SUM(QUANTITY * PRICE_AT_ORDER), 0)
    INTO V_TOTAL
    FROM ORDER_DETAILS
    WHERE ORDER_ID = P_ORDER_ID;

    RETURN V_TOTAL;
END CALCULATE_ORDER_BILL;
/
