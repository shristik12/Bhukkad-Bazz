CREATE OR REPLACE PACKAGE PKG_ORDER_MANAGEMENT AS

    PROCEDURE PLACE_NEW_ORDER (
        P_STUDENT_ID IN NUMBER,
        P_FOOD_ID IN NUMBER,
        P_QUANTITY IN NUMBER,
        P_ORDER_ID OUT NUMBER,
        P_TOTAL OUT NUMBER
    );

    PROCEDURE UPDATE_ORDER_STATUS (
        P_ORDER_ID IN NUMBER,
        P_NEW_STATUS IN VARCHAR2
    );

END PKG_ORDER_MANAGEMENT;
/

CREATE OR REPLACE PACKAGE BODY PKG_ORDER_MANAGEMENT AS

    -- Procedure 1: Place a new order
    PROCEDURE PLACE_NEW_ORDER (
        P_STUDENT_ID IN NUMBER,
        P_FOOD_ID IN NUMBER,
        P_QUANTITY IN NUMBER,
        P_ORDER_ID OUT NUMBER,
        P_TOTAL OUT NUMBER
    )
    IS
    BEGIN
        PLACE_ORDER(
            P_STUDENT_ID,
            P_FOOD_ID,
            P_QUANTITY,
            P_ORDER_ID,
            P_TOTAL
        );
    END PLACE_NEW_ORDER;


    -- Procedure 2: Update order status
    PROCEDURE UPDATE_ORDER_STATUS (
        P_ORDER_ID IN NUMBER,
        P_NEW_STATUS IN VARCHAR2
    )
    IS
    BEGIN
        UPDATE ORDERS
        SET ORDER_STATUS = UPPER(P_NEW_STATUS)
        WHERE ORDER_ID = P_ORDER_ID;

        IF SQL%ROWCOUNT = 0 THEN
            RAISE_APPLICATION_ERROR(
                -20020,
                'Order ID not found.'
            );
        END IF;

        DBMS_OUTPUT.PUT_LINE(
            'Order status updated successfully.'
        );

    END UPDATE_ORDER_STATUS;

END PKG_ORDER_MANAGEMENT;
/




