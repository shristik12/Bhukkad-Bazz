SELECT
    F.FOOD_ID,
    F.FOOD_NAME,
    SUM(D.QUANTITY) AS TOTAL_QUANTITY_SOLD,
    SUM(D.QUANTITY * D.PRICE_AT_ORDER) AS TOTAL_REVENUE
FROM FOOD_ITEMS F
JOIN ORDER_DETAILS D
    ON F.FOOD_ID = D.FOOD_ID
JOIN ORDERS O
    ON D.ORDER_ID = O.ORDER_ID
WHERE O.ORDER_STATUS <> 'CANCELLED'
GROUP BY F.FOOD_ID, F.FOOD_NAME
ORDER BY TOTAL_QUANTITY_SOLD DESC;


SELECT
    S.STUDENT_ID,
    S.STUDENT_NAME,
    COUNT(O.ORDER_ID) AS TOTAL_ORDERS,
    SUM(O.TOTAL_AMOUNT) AS TOTAL_SPENDING
FROM STUDENTS S
JOIN ORDERS O
    ON S.STUDENT_ID = O.STUDENT_ID
WHERE O.ORDER_STATUS <> 'CANCELLED'
GROUP BY S.STUDENT_ID, S.STUDENT_NAME
ORDER BY TOTAL_SPENDING DESC;


SELECT
    TRUNC(ORDER_DATE) AS ORDER_DAY,
    COUNT(*) AS TOTAL_ORDERS,
    SUM(TOTAL_AMOUNT) AS DAILY_REVENUE,
    ROUND(AVG(TOTAL_AMOUNT), 2) AS AVERAGE_ORDER_VALUE
FROM ORDERS
WHERE ORDER_STATUS IN ('COMPLETED', 'READY')
GROUP BY TRUNC(ORDER_DATE)
ORDER BY ORDER_DAY;

SELECT
    F.CATEGORY,
    SUM(D.QUANTITY) AS ITEMS_SOLD,
    SUM(D.QUANTITY * D.PRICE_AT_ORDER) AS CATEGORY_REVENUE
FROM FOOD_ITEMS F
JOIN ORDER_DETAILS D
    ON F.FOOD_ID = D.FOOD_ID
JOIN ORDERS O
    ON D.ORDER_ID = O.ORDER_ID
WHERE O.ORDER_STATUS <> 'CANCELLED'
GROUP BY F.CATEGORY
ORDER BY CATEGORY_REVENUE DESC;

SELECT
    FOOD_ID,
    FOOD_NAME,
    STOCK_QUANTITY,
    PRICE,
    CASE
        WHEN STOCK_QUANTITY = 0 THEN 'OUT OF STOCK'
        WHEN STOCK_QUANTITY <= 10 THEN 'CRITICAL'
        WHEN STOCK_QUANTITY <= 20 THEN 'LOW STOCK'
        ELSE 'AVAILABLE'
    END AS STOCK_STATUS
FROM FOOD_ITEMS
ORDER BY STOCK_QUANTITY ASC;

SELECT
    PAYMENT_METHOD,
    COUNT(*) AS TOTAL_TRANSACTIONS,
    SUM(PAYMENT_AMOUNT) AS TOTAL_COLLECTION
FROM PAYMENTS
WHERE PAYMENT_STATUS = 'SUCCESS'
GROUP BY PAYMENT_METHOD
ORDER BY TOTAL_COLLECTION DESC;

SELECT
    TO_CHAR(PAYMENT_DATE, 'MON-YYYY') AS SALES_MONTH,
    COUNT(PAYMENT_ID) AS TOTAL_PAYMENTS,
    SUM(PAYMENT_AMOUNT) AS MONTHLY_REVENUE
FROM PAYMENTS
WHERE PAYMENT_STATUS = 'SUCCESS'
GROUP BY TO_CHAR(PAYMENT_DATE, 'MON-YYYY'),
         TO_CHAR(PAYMENT_DATE, 'YYYY-MM')
ORDER BY TO_CHAR(PAYMENT_DATE, 'YYYY-MM');


CREATE OR REPLACE VIEW VW_ORDER_SUMMARY AS
SELECT
    O.ORDER_ID,
    S.STUDENT_NAME,
    O.ORDER_DATE,
    O.TOTAL_AMOUNT AS ORIGINAL_AMOUNT,
    P.PAYMENT_AMOUNT AS AMOUNT_PAID,
    P.PAYMENT_METHOD,
    P.PAYMENT_STATUS,
    O.ORDER_STATUS
FROM ORDERS O
JOIN STUDENTS S
    ON O.STUDENT_ID = S.STUDENT_ID
LEFT JOIN PAYMENTS P
    ON O.ORDER_ID = P.ORDER_ID;
SELECT * FROM VW_ORDER_SUMMARY
ORDER BY ORDER_ID;